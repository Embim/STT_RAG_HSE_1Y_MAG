"""Кастомный LLM-судья для разбора качества ASR-транскрипций.

Качество ASR на доменных русскоязычных лекциях нельзя адекватно мерить только
WER/CER — они одинаково штрафуют любую перестановку слов, тогда как практически
важно отличить:

  - **terminology** — модель распознала технический термин как обычное слово
    (например "батч-норм" → "бачковский норм");
  - **hallucination** — ASR вставил отсутствующие в аудио слова;
  - **grammar** — порванный синтаксис / оборванные предложения;
  - **gap** — модель пропустила фрагмент (truncation, обрыв на середине фразы).

Эти 4 категории судит Qwen3-8B с reasoning mode (`<think>...</think>`):
prompt → reasoning_content (видим как думает) + content (JSON findings).
Видимый reasoning — критичен для tuning'а промпта, иначе непонятно почему
модель ошибается в классификации.

Два режима источника:

  - `benchmark` — построчно из CSV `data/eval/results/asr_*.csv`. У каждой
    строки есть reference и hypothesis — судья видит обе и считает дельту.
  - `lecture` — JSON-транскрипция целиком из `data/transcripts/`.
    Reference-free: судья ищет ошибки по внутренней связности и доменным
    знаниям.

Промпты лежат в `prompts/judge/*.yaml`, версионируются в git, выбираются
через `--prompt-version v1`. Итерация: правишь yaml → реран → diff.
"""
